import '../schema/column.dart';

/// Database names become Dart source identifiers and string literals.
/// Reject names that cannot be represented safely by this simple generator.
void validateGeneratedNames(String tableName, List<Column> columns) {
  final name = RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$');
  const dartKeywords = {
    'abstract',
    'as',
    'assert',
    'async',
    'await',
    'base',
    'break',
    'case',
    'catch',
    'class',
    'const',
    'continue',
    'covariant',
    'default',
    'deferred',
    'do',
    'dynamic',
    'else',
    'enum',
    'export',
    'extends',
    'extension',
    'external',
    'factory',
    'false',
    'final',
    'finally',
    'for',
    'Function',
    'get',
    'hide',
    'if',
    'implements',
    'import',
    'in',
    'interface',
    'is',
    'late',
    'library',
    'mixin',
    'new',
    'null',
    'on',
    'operator',
    'part',
    'required',
    'rethrow',
    'return',
    'sealed',
    'set',
    'show',
    'static',
    'super',
    'switch',
    'sync',
    'this',
    'throw',
    'true',
    'try',
    'typedef',
    'var',
    'void',
    'when',
    'while',
    'with',
    'yield',
  };
  if (!name.hasMatch(tableName) ||
      columns.any((column) =>
          !name.hasMatch(column.name) || dartKeywords.contains(column.name))) {
    throw ArgumentError('Table and column names must be simple identifiers.');
  }
}
